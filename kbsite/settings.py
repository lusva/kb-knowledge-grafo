# Chiave di firma delle sessioni. Non sta nel codice: viene generata al primo
# avvio in data/secret_key.txt (leggibile solo dall'utente). Con la chiave in
# chiaro nel sorgente chiunque ne avesse una copia potrebbe forgiare il cookie
# di sessione di questa installazione.
def _secret_key() -> str:
    da_ambiente = os.getenv("KB_SECRET_KEY", "")
    if da_ambiente:
        return da_ambiente
    percorso = Path(os.getenv("KB_DATA_DIR", BASE_DIR / "data")) / "secret_key.txt"
    percorso.parent.mkdir(parents=True, exist_ok=True)
    if not percorso.exists():
        import secrets
        percorso.write_text(secrets.token_urlsafe(64), encoding="utf-8")
        percorso.chmod(0o600)
    return percorso.read_text(encoding="utf-8").strip()


SECRET_KEY = _secret_key()

