# Variabili di questa installazione in .env, nel progetto ed escluso da git
# (modello in .env.example): server LLM e modelli. Le legge Django stesso, così
# valgono uguali con avvia.command, con il debugger di VS Code e con i comandi
# da terminale. Una variabile già nell'ambiente vince (es. KB_LLM_URL= davanti
# a un comando). I test non lo leggono: girano uguali su ogni Mac e in CI.
def _carica_env(percorso: Path) -> None:
    if not percorso.is_file():
        return
    for riga in percorso.read_text(encoding="utf-8").splitlines():
        riga = riga.strip().removeprefix("export ").strip()
        if not riga or riga.startswith("#") or "=" not in riga:
            continue
        chiave, valore = (x.strip() for x in riga.split("=", 1))
        if len(valore) >= 2 and valore[0] == valore[-1] and valore[0] in "\"'":
            valore = valore[1:-1]
        else:
            valore = valore.split(" #", 1)[0].strip()    # commento in fondo alla riga
        os.environ.setdefault(chiave, valore)


if sys.argv[1:2] != ["test"]:
    _carica_env(BASE_DIR / ".env")


